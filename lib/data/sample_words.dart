VocabularyWord w(String topic, String word, String vi, String emoji, String sentence, int index) {
  return VocabularyWord(
    id: '${topic}_$word'.replaceAll(' ', '_').toLowerCase(),
    word: word,
    meaningVi: vi,
    emoji: emoji,
    topic: topic,
    simpleSentence: sentence,
    difficulty: index < 4 ? 1 : index < 8 ? 2 : 3,
  );
}

